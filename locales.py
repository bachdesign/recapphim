def _(key: str, lang: str = "zh", **fmt) -> str:
    """Translate a key into the given language, optionally formatting with kwargs."""
    text = LOCALES.get(lang, LOCALES["zh"]).get(key, key)
    if fmt:
        try:
            text = text.format(**fmt)
        except KeyError:
            pass
    return text

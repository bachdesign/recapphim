import os
import subprocess
from pathlib import Path

def format_timestamp(ms: int) -> str:
    """
    Converts milliseconds into standard SRT format: HH:MM:SS,mmm
    """
    seconds, ms = divmod(int(ms), 1000)
    minutes, seconds = divmod(seconds, 60)
    hours, minutes = divmod(minutes, 60)
    return f"{hours:02d}:{minutes:02d}:{seconds:02d},{ms:03d}"

def extract_audio(video_path: str, audio_path: str):
    """
    Extracts 16kHz mono audio from the video file using FFmpeg.
    16kHz mono is the optimal format for ASR models.
    """
    print(f"[*] Extracting audio from {video_path}...")
    command = [
        "ffmpeg", "-y", "-i", video_path,
        "-vn", "-acodec", "pcm_s16le",
        "-ar", "16000", "-ac", "1", audio_path
    ]
    try:
        # Run FFmpeg silently, throw exception on failure
        subprocess.run(command, stdout=subprocess.DEVNULL, stderr=subprocess.PIPE, check=True)
        print("[*] Audio extraction successful.")
    except subprocess.CalledProcessError as e:
        print(f"FFmpeg error: {e.stderr.decode()}")
        raise RuntimeError("Failed to extract audio. Please ensure FFmpeg is installed and added to your system PATH.")

def generate_srt_from_audio(audio_path: str, srt_path: str):
    """
    Transcribes the audio using FunASR and writes the output directly to an SRT file.
    """
    try:
        from funasr import AutoModel
    except ImportError:
        raise ImportError("Please install FunASR and its dependencies: pip install funasr modelscope torchaudio")

    print("[*] Initializing FunASR model (this may take a moment to download weights on first run)...")
    
    # We use paraformer with VAD and Punctuation models. 
    # VAD is strictly required to get accurate sentence-level timestamp boundaries.
    model = AutoModel(
        model="paraformer-zh",
        vad_model="fsmn-vad",
        punc_model="ct-punc",
        disable_update=True
    )

    print("[*] Transcribing audio...")
    # sentence_timestamp=True forces the model to return precise start/end times
    res = model.generate(
        input=audio_path,
        batch_size_s=300,
        sentence_timestamp=True
    )

    if not res or len(res) == 0:
        raise ValueError("No transcription results were returned from the model.")

    data = res[0]
    
    # Extract the sentence boundary array generated by FunASR
    sentence_info = data.get("sentence_info", [])

    if not sentence_info:
        raise ValueError("The model did not return sentence boundaries. Ensure VAD is functioning properly.")

    print(f"[*] Writing SRT file to {srt_path}...")
    with open(srt_path, "w", encoding="utf-8") as f:
        for i, seg in enumerate(sentence_info, start=1):
            start_time = format_timestamp(seg.get("start", 0))
            end_time = format_timestamp(seg.get("end", 0))
            text = seg.get("text", "").strip()

            # SRT Format Structure:
            # 1
            # 00:00:00,000 --> 00:00:02,500
            # Subtitle text
            f.write(f"{i}\n")
            f.write(f"{start_time} --> {end_time}\n")
            f.write(f"{text}\n\n")

    print("[*] SRT generation complete!")

def process_video(video_file: str):
    """
    Main orchestrator function.
    """
    if not os.path.exists(video_file):
        raise FileNotFoundError(f"Video file not found: {video_file}")

    # Set up file paths dynamically based on the input video
    base_name = os.path.splitext(video_file)[0]
    audio_file = f"{base_name}_extracted.wav"
    srt_file = f"{base_name}.srt"

    try:
        # 1. Extract the audio
        extract_audio(video_file, audio_file)
        
        # 2. Transcribe and generate SRT
        generate_srt_from_audio(audio_file, srt_file)
        
    finally:
        # 3. Cleanup: remove the temporary huge WAV file to save disk space
        if os.path.exists(audio_file):
            os.remove(audio_file)
            print("[*] Cleaned up temporary audio file.")
            
    print(f"\nSUCCESS: Your subtitles are ready at -> {srt_file}")


